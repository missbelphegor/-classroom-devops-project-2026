/*
# Classroom Issue Reporting System - Initial Schema

1. Purpose
   - Stores issues reported by students/faculty about classroom problems.
   - Tracks status changes and maintenance remarks on each issue.
   - Single-tenant app (no auth) — anon and authenticated roles can CRUD all data.

2. New Tables
   - `issues`: each row is a classroom issue report.
     - `id` uuid PK
     - `issue_code` text unique (e.g. CR-1001), generated via sequence
     - `reporter_name` text NOT NULL
     - `reporter_email` text NOT NULL
     - `reporter_role` text (Student/Faculty/Staff)
     - `classroom_number` text NOT NULL
     - `building` text NOT NULL
     - `category` text NOT NULL
     - `priority` text NOT NULL (Low, Medium, High, Critical)
     - `description` text NOT NULL
     - `status` text NOT NULL DEFAULT 'Reported' (Reported, Assigned, In Progress, Resolved, Rejected)
     - `assigned_to` text
     - `image_url` text
     - `reported_at` timestamptz NOT NULL DEFAULT now()
     - `updated_at` timestamptz DEFAULT now()
   - `issue_updates`: audit trail of status changes and remarks.
     - `id` uuid PK
     - `issue_id` uuid FK -> issues(id) ON DELETE CASCADE
     - `previous_status` text
     - `new_status` text
     - `remark` text
     - `updated_by` text
     - `created_at` timestamptz DEFAULT now()

3. Security
   - RLS enabled on `issues` and `issue_updates`.
   - Anon + authenticated roles have full CRUD (single-tenant, intentionally public data).
   - Storage bucket `issue-images` is public for reads, anon+authenticated for writes.

4. Notes
   - `issue_code` is generated by a trigger that formats the next sequence value as 'CR-NNNN'.
*/

CREATE TABLE IF NOT EXISTS issues (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  issue_code text UNIQUE,
  reporter_name text NOT NULL,
  reporter_email text NOT NULL,
  reporter_role text DEFAULT 'Student',
  classroom_number text NOT NULL,
  building text NOT NULL,
  category text NOT NULL,
  priority text NOT NULL,
  description text NOT NULL,
  status text NOT NULL DEFAULT 'Reported',
  assigned_to text,
  image_url text,
  reported_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS issue_updates (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  issue_id uuid NOT NULL REFERENCES issues(id) ON DELETE CASCADE,
  previous_status text,
  new_status text,
  remark text,
  updated_by text,
  created_at timestamptz DEFAULT now()
);

-- Sequence for issue codes starting at 1001
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_sequences WHERE schemaname = 'public' AND sequencename = 'issue_code_seq') THEN
    CREATE SEQUENCE issue_code_seq START 1001;
  END IF;
END $$;

-- Function to generate issue code from sequence
CREATE OR REPLACE FUNCTION generate_issue_code()
RETURNS text AS $$
DECLARE
  next_val bigint;
BEGIN
  next_val := nextval('issue_code_seq');
  RETURN 'CR-' || next_val::text;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Trigger function to set issue_code on insert
CREATE OR REPLACE FUNCTION set_issue_code_from_seq()
RETURNS trigger AS $$
BEGIN
  NEW.issue_code := generate_issue_code();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Trigger to auto-generate issue_code on insert
DROP TRIGGER IF EXISTS set_issue_code ON issues;
CREATE TRIGGER set_issue_code
  BEFORE INSERT ON issues
  FOR EACH ROW
  WHEN (NEW.issue_code IS NULL)
  EXECUTE FUNCTION set_issue_code_from_seq();

-- Trigger function to update updated_at on update
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS trigger AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS update_issues_updated_at ON issues;
CREATE TRIGGER update_issues_updated_at
  BEFORE UPDATE ON issues
  FOR EACH ROW
  EXECUTE FUNCTION update_updated_at_column();

-- Enable RLS
ALTER TABLE issues ENABLE ROW LEVEL SECURITY;
ALTER TABLE issue_updates ENABLE ROW LEVEL SECURITY;

-- Issues policies (anon + authenticated, single-tenant)
DROP POLICY IF EXISTS "anon_select_issues" ON issues;
CREATE POLICY "anon_select_issues" ON issues FOR SELECT
  TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "anon_insert_issues" ON issues;
CREATE POLICY "anon_insert_issues" ON issues FOR INSERT
  TO anon, authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "anon_update_issues" ON issues;
CREATE POLICY "anon_update_issues" ON issues FOR UPDATE
  TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "anon_delete_issues" ON issues;
CREATE POLICY "anon_delete_issues" ON issues FOR DELETE
  TO anon, authenticated USING (true);

-- Issue updates policies
DROP POLICY IF EXISTS "anon_select_issue_updates" ON issue_updates;
CREATE POLICY "anon_select_issue_updates" ON issue_updates FOR SELECT
  TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "anon_insert_issue_updates" ON issue_updates;
CREATE POLICY "anon_insert_issue_updates" ON issue_updates FOR INSERT
  TO anon, authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "anon_update_issue_updates" ON issue_updates;
CREATE POLICY "anon_update_issue_updates" ON issue_updates FOR UPDATE
  TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "anon_delete_issue_updates" ON issue_updates;
CREATE POLICY "anon_delete_issue_updates" ON issue_updates FOR DELETE
  TO anon, authenticated USING (true);

-- Indexes
CREATE INDEX IF NOT EXISTS idx_issues_status ON issues(status);
CREATE INDEX IF NOT EXISTS idx_issues_priority ON issues(priority);
CREATE INDEX IF NOT EXISTS idx_issues_category ON issues(category);
CREATE INDEX IF NOT EXISTS idx_issues_classroom ON issues(classroom_number);
CREATE INDEX IF NOT EXISTS idx_issues_building ON issues(building);
CREATE INDEX IF NOT EXISTS idx_issue_updates_issue_id ON issue_updates(issue_id);

-- Storage bucket for issue images
INSERT INTO storage.buckets (id, name, public)
VALUES ('issue-images', 'issue-images', true)
ON CONFLICT (id) DO NOTHING;

-- Storage policies
DROP POLICY IF EXISTS "anon_upload_issue_images" ON storage.objects;
CREATE POLICY "anon_upload_issue_images" ON storage.objects
  FOR INSERT TO anon, authenticated
  WITH CHECK (bucket_id = 'issue-images');

DROP POLICY IF EXISTS "anon_read_issue_images" ON storage.objects;
CREATE POLICY "anon_read_issue_images" ON storage.objects
  FOR SELECT TO anon, authenticated
  USING (bucket_id = 'issue-images');

DROP POLICY IF EXISTS "anon_delete_issue_images" ON storage.objects;
CREATE POLICY "anon_delete_issue_images" ON storage.objects
  FOR DELETE TO anon, authenticated
  USING (bucket_id = 'issue-images');